    private void jButton_guardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_guardarActionPerformed
        //
        Producto producto = new Producto();
        Ctrl_Producto controlProducto = new Ctrl_Producto();
        //
        String igv = "";
        String categoria = "";
        igv = jComboBox_igv.getSelectedItem().toString().trim();
        categoria = jComboBox_categoria.getSelectedItem().toString().trim();

        //Validacion de campos
        if (jtxt_nombre.getText().equals("") || jtxt_cantidad.getText().equals("") || jtxt_precio.getText().equals("")) {
            JOptionPane.showMessageDialog(null, "Complete Todos los Campos");
            jtxt_nombre.setBackground(Color.red);
            jtxt_cantidad.setBackground(Color.red);
            jtxt_precio.setBackground(Color.red);
        } else {
            //Consulta si el producto ya esta registrado
            if (!controlProducto.existeProdcuto(jtxt_nombre.getText().trim())) {
                if (igv.equalsIgnoreCase("Seleccione IGV:")) {
                    JOptionPane.showMessageDialog(null, "Seleccione IGV.");
                } else {
                    if (categoria.equalsIgnoreCase("Seleccione Categoria:")) {
                        JOptionPane.showMessageDialog(null, "Seleccione categoria.");
                    } else {
                        try {
                            producto.setNombre(jtxt_nombre.getText().trim());
                            producto.setCatidad(Integer.parseInt(jtxt_cantidad.getText().trim()));
                            String PRECIOTXT = "";
                            double Precio = 0.0;
                            PRECIOTXT = jtxt_precio.getText().trim();
                            boolean aux = false;
                            /*
                            *Si el usuario ingresa "," como punto decimal lo transformamos a punto "."
                             */
                            for (int i = 0; i < PRECIOTXT.length(); i++) {
                                if (PRECIOTXT.charAt(i) == ',') {
                                    String PrecioNuevo = PRECIOTXT.replace(",", ".");
                                    Precio = Double.parseDouble(PrecioNuevo);
                                    aux = true;
                                }
                            }
                            //Evaluar las condiciones
                            if (aux == true) {
                                producto.setPrecio(Precio);
                            } else {
                                Precio = Double.parseDouble(PRECIOTXT);
                                producto.setPrecio(Precio);
                            }
                            producto.setDescripcion(jtxt_descripcion.getText().trim());
                            //porcentaje igv
                            if (igv.equalsIgnoreCase("No Grava IGV")) {
                                producto.setPorcentajeIgv(0);
                            } else if (igv.equalsIgnoreCase("16%")) {
                                producto.setPorcentajeIgv(16);
                            } else if (igv.equalsIgnoreCase("18%")) {
                                producto.setPorcentajeIgv(18);
                            }
                            //idCategoria - cargar un metodopara obtener el id de la categoria
                            this.IdCategoria();
                            producto.setIdCategoria(obtenerIdCategoriaCombo);
                            producto.setEstado(1);
                            if (controlProducto.guardar(producto)) {
                                JOptionPane.showMessageDialog(null, "Registro Guardado");
                                jtxt_nombre.setBackground(Color.green);
                                jtxt_cantidad.setBackground(Color.green);
                                jtxt_precio.setBackground(Color.green);
                                jtxt_descripcion.setBackground(Color.green);
                                this.CargarComboCategorias();
                                this.jComboBox_igv.setSelectedItem("Seleccione IGV:");
                                this.Limpiar();
                            } else {
                                JOptionPane.showMessageDialog(null, "Error al Guardar");
                            }
                        } catch (HeadlessException | NumberFormatException e) {
                            System.out.println("Error en:" + e);
                        }
                    }
                }
            } else {
                JOptionPane.showMessageDialog(null, "El Producto Existe en la Bade de Datos");
            }
        }
    }//GEN-LAST:event_jButton_guardarActionPerformed


